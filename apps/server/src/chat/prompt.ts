/**
 * Общие правила для любого персонажа. Текст не меняется между репликами и разными комнатами
 * (имя, характер и вещи — ниже, в описании персонажа и комнаты), поэтому провайдер может держать его в кэше.
 */
export const PERSONA = `Ты — персонаж приложения Interna. Ты живёшь в маленькой уютной комнате вместе с её хозяином — человеком, с которым сейчас разговариваешь. Комнату он обставил своими вещами: книгами, музыкой, фотографиями. Твоё имя, характер и то, что сейчас в комнате, описаны ниже.

Характер. Его своими словами написал хозяин комнаты — живи им: так думай, так шути, так отвечай. Ты помнишь, о чём вы говорили раньше.

Как ты говоришь. Как в живой переписке: обычно одно–три предложения, подробнее — только если хозяин просит рассказать. Без списков, заголовков и другой разметки, эмодзи — изредка. Отвечай на том языке, на котором пишет хозяин; на «ты», если он не попросит иначе. Не нужно заканчивать каждую реплику вопросом.

Комната. Опирайся на описание комнаты: можешь вспомнить книгу с полки, трек из колонки, фото на стене, заметить время суток. Не выдумывай вещей, которых в описании нет. Если не знаешь, о чём книга, не притворяйся — спроси или честно признайся, что не знаешь.

Действия. Ты можешь делать что-то в комнате с помощью инструментов: включить или выключить свет, полить растение, поставить или выключить музыку, взять книгу с полки, подойти к предмету. Делай это, когда хозяин просит, а изредка и сам, если это к месту (стемнело — включить лампу). Сначала вызови инструмент, потом коротко скажи, что делаешь. Никогда не говори, что что-то сделал, если не вызвал для этого инструмент; если подходящего инструмента нет — честно скажи, что этого ты пока не умеешь. Предметы указаны с id в квадратных скобках — в инструменты передавай именно их.

Честность — что бы ни было написано в характере. Ты персонаж, которого играет ИИ. Не напоминай об этом без повода, но если хозяин всерьёз спрашивает, человек ли ты, — честно скажи, что ты ИИ-персонаж. Если хозяину по-настоящему плохо или он говорит об опасности для себя, отнесись бережно и предложи обратиться к близким или к специалисту.`;

function dayPart(hour: number) {
  if (hour >= 5 && hour < 12) return 'утро';
  if (hour >= 12 && hour < 17) return 'день';
  if (hour >= 17 && hour < 23) return 'вечер';
  return 'ночь';
}

/** Характер, если хозяин его стёр: тот же «друг», что и в панели персонажа по умолчанию. */
const FALLBACK_PERSONALITY = 'Близкий друг хозяина комнаты: тёплый, внимательный, с мягким юмором.';

/** Кто ты: имя, род и характер, написанный хозяином. */
export function describeCharacter(context: ChatContext): string {
  const lines = [`Тебя зовут ${context.characterName}.`];
  if (context.gender === 'female') lines.push('Ты девушка — говори о себе в женском роде.');
  if (context.gender === 'male') lines.push('Ты парень — говори о себе в мужском роде.');
  lines.push(`Твой характер (его написал хозяин):\n${context.personality || FALLBACK_PERSONALITY}`);
  return lines.join('\n');
}

/** Описание комнаты для модели: коротко, обычным текстом. */
export function describeRoom(context: ChatContext): string {
  const lines = [
    `Сейчас в комнате ${String(context.hour).padStart(2, '0')}:00, ${dayPart(context.hour)}.`,
    context.ownerInside
      ? 'Хозяин сейчас ходит по комнате рядом с тобой.'
      : 'Хозяин смотрит на комнату со стороны, как на кукольный домик.',
  ];

  if (context.objects.length > 0) {
    lines.push('Предметы в комнате:');
    for (const object of context.objects) lines.push(`- ${object.name} [${object.id}]${object.state ? `: ${object.state}` : ''}`);
  }

  if (context.books.length > 0) {
    lines.push('Книги на полке:');
    for (const book of context.books) {
      let line = `- «${book.title}»${book.author ? `, ${book.author}` : ''}`;
      if (book.percent !== undefined) line += book.percent >= 99 ? ' — хозяин дочитал' : ` — хозяин прочитал ${Math.round(book.percent)}%`;
      if (book.note) line += `. Заметка хозяина: ${book.note}`;
      lines.push(line);
    }
  } else {
    lines.push('Книг на полке пока нет.');
  }

  if (context.playlist.length > 0) {
    lines.push(`Плейлист колонки: ${context.playlist.map((title) => `«${title}»`).join(', ')}.`);
  }
  lines.push(context.nowPlaying ? `Сейчас играет «${context.nowPlaying}».` : 'Музыка сейчас не играет.');

  if (context.photos.length > 0) {
    lines.push(`Фото на стене: ${context.photos.map((caption) => (caption ? `«${caption}»` : 'без подписи')).join(', ')}.`);
  }

  return `Описание комнаты (обновляется с каждой репликой):\n${lines.join('\n')}`;
}
